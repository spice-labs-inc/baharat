    private final int tag;

    HeaderTag(int tag) {
        this.tag = tag;
    }

    /**
     * Returns the numeric tag value.
     *
     * @return the tag number
     */
    public int tag() {
        return tag;
    }

    /**
     * Looks up a header tag by its numeric value.
     *
     * @param tag the tag number
     * @return an Optional containing the tag, or empty if unknown
     */
    public static @NotNull Optional<HeaderTag> fromTag(int tag) {
        for (HeaderTag headerTag : values()) {
            if (headerTag.tag == tag) {
                return Optional.of(headerTag);
            }
        }
        return Optional.empty();
    }
